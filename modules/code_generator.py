    @staticmethod
    def _clean_var_name(text: str) -> str:
        cleaned = re.sub(r"(?i)^(input|read|get|enter|prompt)\s*", "", text).strip()
        cleaned = re.sub(r"[^\w]", "_", cleaned)
        if not cleaned or cleaned[0].isdigit():
            cleaned = "num_" + cleaned
        return cleaned

    @classmethod
    def generate_all(cls, ir: FlowchartIR) -> Dict[str, str]:
        return {
            SupportedLanguage.PYTHON.value: cls.generate_python(ir),
            SupportedLanguage.CPP.value: cls.generate_cpp(ir),
            SupportedLanguage.JAVA.value: cls.generate_java(ir),
            SupportedLanguage.JAVASCRIPT.value: cls.generate_javascript(ir),
            SupportedLanguage.C.value: cls.generate_c(ir),
            SupportedLanguage.GO.value: cls.generate_go(ir),
            SupportedLanguage.RUST.value: cls.generate_rust(ir),
        }

    # -- Python --
    @classmethod
    def generate_python(cls, ir: FlowchartIR) -> str:
        lines = [
            "# Generated by FlowLogic AI Studio (Deterministic Engine)",
            "# Language: Python 3",
            "",
            "def main():",
        ]
        indent = "    "
        branch_targets = set()
        for node in ir.nodes:
          branch_targets.update(node.branch_conditions.values())
        for n in sorted(ir.nodes, key=lambda x: x.id, reverse=True):
            if n.id in branch_targets:
               continue
            if n.node_type == FlowNodeType.START:
                lines.append(f"{indent}# --- Start of Program ---")
            elif n.node_type == FlowNodeType.INPUT:
                var = cls._clean_var_name(n.raw_text)
                lines.append(f"{indent}{var} = float(input('Enter {var}: '))")
            elif n.node_type == FlowNodeType.DECISION:
                cond = n.cleaned_expression or "True"
                lines.append(f"{indent}# Decision Block")
                lines.append(f"{indent}if {cond}:")
                yes_tgt = n.branch_conditions.get("Yes")
                if yes_tgt is not None and yes_tgt < len(ir.nodes):
                    lines.append(f"{indent}    print('{ir.nodes[yes_tgt].cleaned_expression}')")
                else:
                    lines.append(f"{indent}    pass")
                lines.append(f"{indent}else:")
                no_tgt = n.branch_conditions.get("No")
                if no_tgt is not None and no_tgt < len(ir.nodes):
                    lines.append(f"{indent}    print('{ir.nodes[no_tgt].cleaned_expression}')")
                else:
                    lines.append(f"{indent}    pass")
            elif n.node_type == FlowNodeType.OUTPUT:
                clean = n.cleaned_expression.replace("Print", "").replace("print", "").replace("output", "").strip(" ('\")")
                lines.append(f"{indent}print({clean})")
            elif n.node_type == FlowNodeType.PROCESS:
                lines.append(f"{indent}{n.cleaned_expression}")
            elif n.node_type == FlowNodeType.END:
                lines.append(f"{indent}# --- End of Program ---")

        lines.extend([
            "",
            "if __name__ == '__main__':",
            "    main()",
        ])
        return "\n".join(lines)

    # -- C++ --
    @classmethod
    def generate_cpp(cls, ir: FlowchartIR) -> str:
        lines = [
            "// Generated by FlowLogic AI Studio",
            "// Language: C++17",
            "#include <iostream>",
            "#include <string>",
            "using namespace std;",
            "",
            "int main() {",
        ]

        indent = "    "
        branch_targets = set()

        for node in ir.nodes:
            branch_targets.update(node.branch_conditions.values())

        declared = set()

        for n in sorted(ir.nodes, key=lambda x: x.id, reverse=True):

            if n.id in branch_targets:
                continue

            if n.node_type == FlowNodeType.INPUT:
                var = cls._clean_var_name(n.raw_text)

                if var not in declared:
                    lines.append(f"{indent}double {var};")
                    declared.add(var)

                lines.append(f'{indent}cout << "Enter {var}: ";')
                lines.append(f"{indent}cin >> {var};")

            elif n.node_type == FlowNodeType.DECISION:
                cond = n.cleaned_expression or "true"

                lines.append(f"{indent}if ({cond}) {{")

                yes_tgt = n.branch_conditions.get("Yes")
                if yes_tgt is not None and yes_tgt < len(ir.nodes):
                    text = ir.nodes[yes_tgt].cleaned_expression
                    lines.append(f'{indent}    cout << "{text}" << endl;')

                lines.append(f"{indent}}} else {{")

                no_tgt = n.branch_conditions.get("No")
                if no_tgt is not None and no_tgt < len(ir.nodes):
                    text = ir.nodes[no_tgt].cleaned_expression
                    lines.append(f'{indent}    cout << "{text}" << endl;')

                lines.append(f"{indent}}}")

            elif n.node_type == FlowNodeType.OUTPUT:
                clean = (
                    n.cleaned_expression
                    .replace("Print", "")
                    .replace("print", "")
                    .replace("Output", "")
                    .replace("output", "")
                    .strip(" ('\")")
                )

                lines.append(f"{indent}cout << {clean} << endl;")

            elif n.node_type == FlowNodeType.PROCESS:
                expression = n.cleaned_expression.strip()

                match = re.match(
                    r"^\s*([A-Za-z_]\w*)\s*=\s*(.+?)\s*;?\s*$",
                    expression
                )

                if match:
                    variable = match.group(1)
                    value = match.group(2).strip()

                    if variable not in declared:
                        lines.append(
                            f"{indent}double {variable} = {value};"
                        )
                        declared.add(variable)
                    else:
                        lines.append(
                            f"{indent}{variable} = {value};"
                        )
                else:
                    lines.append(f"{indent}{expression};")

        lines.extend([
            f"{indent}return 0;",
            "}",
        ])

        return "\n".join(lines)


