class CodeGenerator:
    """
    Main Code Generation Facade.
    Combines Deterministic Transpilation, AI Generation (optional), Complexity Analysis, and Unit Tests.
    """

    def __init__(self, api_key: Optional[str] = None, provider: str = "none"):
        self.api_key = api_key
        self.provider = provider.lower()

    def generate(self, ir: FlowchartIR, active_language: str = "Python") -> GeneratedCodeResult:
        """Produces full polyglot output with complexity analysis and test cases."""
        # 1. Generate multi-language code using deterministic builder
        codes = DeterministicCodeBuilder.generate_all(ir)
        engine_used = "Deterministic AST Engine"

        # 2. If API Key provided, attempt AI refinement
        if self.api_key and self.provider in ["gemini", "openai"]:
            ai_code = self._try_ai_refinement(ir, active_language)
            if ai_code:
                codes[active_language] = ai_code
                engine_used = f"AI / LLM Engine ({self.provider.upper()})"

        # 3. Compute Big-O complexity
        complexity = ComplexityEngine.analyze(ir)

        # 4. Generate line-by-line explanations
        explanations = self._generate_explanations(ir)

        # 5. Generate Unit Test Suite
        test_cases = TestSuiteGenerator.generate(ir)

        return GeneratedCodeResult(
            codes=codes,
            active_language=active_language,
            complexity=complexity,
            line_explanations=explanations,
            test_cases=test_cases,
            engine_used=engine_used,
        )

    def _generate_explanations(self, ir: FlowchartIR) -> List[Dict[str, Any]]:
        exps = []
        for n in ir.nodes:
            exps.append({
                "node_id": n.id,
                "shape": n.shape,
                "type": n.node_type.value,
                "text": n.raw_text,
                "explanation": f"Node #{n.id} ({n.node_type.value}): Translates to '{n.cleaned_expression}' logic in target language.",
            })
        return exps

    def _try_ai_refinement(self, ir: FlowchartIR, lang: str) -> Optional[str]:
        """Calls OpenAI or Gemini API if credentials are supplied."""
        prompt = f"""
        Convert this structured flowchart IR into clean, production-grade {lang} code:
        {ir.to_json()}
        Return ONLY valid {lang} code, without markdown quotes or explanation.
        """
        try:
            if self.provider == "gemini":
                import google.generativeai as genai
                genai.configure(api_key=self.api_key)
                model = genai.GenerativeModel("gemini-1.5-flash")
                response = model.generate_content(prompt)
                return response.text.replace("```python", "").replace("```cpp", "").replace("```java", "").replace("```javascript", "").replace("```", "").strip()
            elif self.provider == "openai":
                import openai
                client = openai.OpenAI(api_key=self.api_key)
                response = client.chat.completions.create(
                    model="gpt-4o-mini",
                    messages=[{"role": "user", "content": prompt}],
                    temperature=0.2,
                )
                return response.choices[0].message.content.replace("```python", "").replace("```", "").strip()
        except Exception:
            return None
        return None
